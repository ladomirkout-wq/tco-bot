                type(sizeArr[1]) ~= "number" or
                type(sizeArr[2]) ~= "number" or
                type(sizeArr[3]) ~= "number" or
                sizeArr[1] <= 0 or sizeArr[2] <= 0 or sizeArr[3] <= 0
            ) then continue end


            local bsz = sizeArr
                and Vector3.new(sizeArr[1], sizeArr[2], sizeArr[3])
                or  Vector3.new(gridSize,   gridSize,   gridSize)


            local colArr = v.c or v.color
            local col    = (colArr and type(colArr[1]) == "number")
                and Color3.fromRGB(colArr[1], colArr[2], colArr[3])
                or  defaultcolor


            local mat  = tostring(v.m or v.mat or "smooth"):lower()
            local anch = v.a  ~= nil and v.a  or true
            local coll = v.cc ~= nil and v.cc or true


            local sprays  = nil
            local rawSp   = v.sp or v.sprayed
            if rawSp then
                sprays = {}
                for _, sp in ipairs(rawSp) do
                    if type(sp[1]) == "string" and Enum.NormalId[sp[1]] then
                        table.insert(sprays, sp)
                    end
                end
                if #sprays == 0 then sprays = nil end
            end


            local isDetail = (
                bsz.X ~= gridSize or
                bsz.Y ~= gridSize or
                bsz.Z ~= gridSize
            )


            table.insert(resolved, {
                p        = { posses[1], posses[2], posses[3] },
                s        = sizeArr,
                bsz      = bsz,
                col      = col,
                mat      = mat,
                anch     = anch,
                coll     = coll,
                sprays   = sprays,
                isDetail = isDetail,
                placed   = false,
            })
        end


        if #resolved == 0 then
            return nil, "Manifest resolved zero valid blocks"
        end


        local rot   = type(parsed) == "table" and parsed.rot or nil
        local off   = type(parsed) == "table" and parsed.off or nil
        local rotCF = (type(rot) == "table" and (rot[1] ~= 0 or rot[2] ~= 0 or rot[3] ~= 0))
            and CFrame.Angles(math.rad(rot[1] or 0), math.rad(rot[2] or 0), math.rad(rot[3] or 0))
            or nil
        local offset = (type(off) == "table")
            and Vector3.new(off[1] or 0, off[2] or 0, off[3] or 0) or nil


        return {
            blocks     = resolved,
            rotCF      = rotCF,
            offset     = offset,
            blockCount = #resolved,
        }
    end


    -- ── Save system ───────────────────────────────────────────────────────────


    function saveBuild(filename)
        local folder = workspace:FindFirstChild("Cubes") or workspace:FindFirstChild("Bricks")
        if not folder then
            chat("❌ No build folder found (Cubes/Bricks)")
            return
        end


        local blocks = {}


        local function collectFrom(container)
            for _, child in ipairs(container:GetChildren()) do
                if child:IsA("BasePart") then
                    local pos = child.Position
                    local sz  = child.Size
                    local isDetail = (
                        sz.X ~= gridSize or
                        sz.Y ~= gridSize or
                        sz.Z ~= gridSize
                    )
                    local block = {}
                    block.a  = child.Anchored
                    block.cc = child.CanCollide
                    if isDetail then
                        block.p = {
                            pos.X - (sz.X / 2) + 0.5,
                            pos.Y - (sz.Y / 2) + 0.5,
                            pos.Z - (sz.Z / 2) + 0.5,
                        }
                        block.s = { sz.X, sz.Y, sz.Z }
                    else
                        block.p = {
                            pos.X - (gridSize / 2) + 0.5,
                            pos.Y - (gridSize / 2) + 0.5,
                            pos.Z - (gridSize / 2) + 0.5,
                        }
                    end
                    block.m = materials[child.Material] or "smooth"
                    block.o = child.Material.Name
                    block.c = {
                        math.round(child.Color.R * 255),
                        math.round(child.Color.G * 255),
                        math.round(child.Color.B * 255),
                    }
                    local sprayData = {}
                    for _, gui in ipairs(child:GetChildren()) do
                        if gui:IsA("SurfaceGui") then
                            local faceName = gui.Face.Name
                            local imageId  = ""
                            local txt      = ""
                            local imgLabel = gui:FindFirstChildWhichIsA("ImageLabel", true)
                            local txtLabel = gui:FindFirstChildWhichIsA("TextLabel", true)
                            if imgLabel then imageId = imgLabel.Image or "" end
                            if txtLabel then txt     = txtLabel.Text  or "" end
                            if txt ~= "" or imageId ~= "" then
                                table.insert(sprayData, { faceName, imageId, txt })
                            end
                        end
                    end
                    if #sprayData > 0 then block.sp = sprayData end
                    table.insert(blocks, block)
                elseif child:IsA("Model") or child:IsA("Folder") then
                    collectFrom(child)
                end
            end
        end


        collectFrom(folder)


        if #blocks == 0 then
            chat("❌ No blocks found to save")
            return
        end


