local griefMessages = {
    ["delete"] = "🚨 GRIEF ALERT: %s is deleting blocks",
    ["paint"]  = "🚨 GRIEF ALERT: %s is grief painting",
    ["build"]  = "🚨 GRIEF ALERT: %s is spamming blocks",
    ["anchor"] = "🚨 GRIEF ALERT: %s is unanchoring blocks",
}


local function isCooledDown(playerName)
    if agCooldownTime == 0 then return true end
    local last = agCooldowns[playerName]
    if not last then return true end
    return tick() - last >= agCooldownTime
end


local function setCooldown(playerName)
    agCooldowns[playerName] = tick()
end


local function isAGWhitelisted(player)
    return agWhitelist[player.Name] == true
end


local function checkTimeFilter(player)
    if agTimeFilter == 0 then return true end
    local ok, val = pcall(function()
        return player.leaderstats.Time.Value
    end)
    return ok and type(val) == "number" and val < agTimeFilter
end


local function checkEnlighten(player)
    if agEnlighten then return true end
    local char = player.Character
    local bp = player.Backpack
    if char and (char:FindFirstChild("The Arkenstone") or (bp and bp:FindFirstChild("The Arkenstone"))) then
        return false
    end
    return true
end


local function shouldDetect(player)
    if not agEnabled then return false end
    if isAGWhitelisted(player) then return false end
    if not checkEnlighten(player) then return false end
    if not checkTimeFilter(player) then return false end
    if not isCooledDown(player.Name) then return false end
    return true
end


local function flagPlayer(player, griefType)
    if not shouldDetect(player) then return end
    setCooldown(player.Name)
    local template = griefMessages[griefType] or "🚨 GRIEF ALERT: %s is griefing"
    chat(string.format(template, player.DisplayName))
end


local agConnections = {}


local function stopAGDetection()
    for _, conn in ipairs(agConnections) do
        conn:Disconnect()
    end
    agConnections = {}
    blockOwners   = {}
    spamCounters  = {}
    agCooldowns   = {}
end


local function startAGDetection()
    stopAGDetection()


    local folder = workspace:FindFirstChild("Cubes") or workspace:FindFirstChild("Bricks")
    if not folder then
        chat("❌ Could not find build folder (Cubes/Bricks)")
        return
    end


    local function trackPlacement(player)
        -- Wait up to 5 seconds for the subfolder to appear
        local playerFolder = folder:FindFirstChild(player.Name)
        if not playerFolder then
            local t0 = tick()
            local waitConn
            waitConn = folder.ChildAdded:Connect(function(child)
                if child.Name == player.Name then
                    waitConn:Disconnect()
                    playerFolder = child
                end
            end)
            repeat task.wait(0.1) until playerFolder or tick() - t0 > 5
            if waitConn then pcall(function() waitConn:Disconnect() end) end
        end


        if not playerFolder then
            -- Game might not use subfolders, watch the root folder instead
            playerFolder = folder
        end


        local conn = playerFolder.ChildAdded:Connect(function(block)
            blockOwners[block] = player.Name


            -- Spam detection
            if agDetectSpam then
                spamCounters[player.Name] = (spamCounters[player.Name] or 0) + 1
                local count = spamCounters[player.Name]
                task.delay(5, function()
                    spamCounters[player.Name] = math.max(0, (spamCounters[player.Name] or 0) - 1)
                end)
                if count >= 10 then
                    spamCounters[player.Name] = 0
                    flagPlayer(player, "build")
                end
            end


            -- Watch the block for changes
            if agDetectDelete then
                local delConn
                delConn = block:GetPropertyChangedSignal("Parent"):Connect(function()
                    if block.Parent == nil then
                        delConn:Disconnect()
                        -- Find the most likely griefer (last active non-owner player)
                        for _, p in ipairs(Players:GetPlayers()) do
                            if p.Name ~= player.Name and p ~= LocalPlayer then
                                if agInGame or p.Parent then
                                    flagPlayer(p, "delete")
                                    break
                                end
                            end
                        end
                    end
                end)
                table.insert(agConnections, delConn)
            end


            if agDetectPaint then
                local paintConn
                paintConn = block:GetPropertyChangedSignal("Color"):Connect(function()
                    for _, p in ipairs(Players:GetPlayers()) do
                        if p.Name ~= player.Name and p ~= LocalPlayer then
                            flagPlayer(p, "paint")
                            break
                        end
                    end
                end)
                table.insert(agConnections, paintConn)
            end


            if agDetectAnchor then
                local anchorConn
                anchorConn = block:GetPropertyChangedSignal("Anchored"):Connect(function()
                    if not block.Anchored then
                        for _, p in ipairs(Players:GetPlayers()) do
                            if p.Name ~= player.Name and p ~= LocalPlayer then
                                flagPlayer(p, "anchor")
                                break
                            end
                        end
                    end
                end)
                table.insert(agConnections, anchorConn)
            end
        end)


        table.insert(agConnections, conn)
    end


    -- Track all current players
    for _, p in ipairs(Players:GetPlayers()) do
        if p ~= LocalPlayer then
            task.spawn(function() trackPlacement(p) end)
        end
    end


    -- Track players who join later
    local joinConn = Players.PlayerAdded:Connect(function(p)
        if p ~= LocalPlayer then
            task.spawn(function()
                task.wait(2) -- give time for their folder to be created
                trackPlacement(p)
            end)
        end
    end)
    table.insert(agConnections, joinConn)


    chat("✅ Anti-grief detection started")
end


