    function computeBuildCenter(blocks)
        local minV, maxV
        for _, block in ipairs(blocks) do
            local p = block.p
            if p then
                local s  = block.s
                local cx = p[1] + (s and (s[1] / 2 - 0.5) or 0)
                local cy = p[2] + (s and (s[2] / 2 - 0.5) or 0)
                local cz = p[3] + (s and (s[3] / 2 - 0.5) or 0)
                if not minV then
                    minV = {cx, cy, cz}; maxV = {cx, cy, cz}
                else
                    minV[1] = math.min(minV[1], cx); maxV[1] = math.max(maxV[1], cx)
                    minV[2] = math.min(minV[2], cy); maxV[2] = math.max(maxV[2], cy)
                    minV[3] = math.min(minV[3], cz); maxV[3] = math.max(maxV[3], cz)
                end
            end
        end
        if not minV then return Vector3.zero end
        return Vector3.new(
            (minV[1] + maxV[1]) / 2,
            (minV[2] + maxV[2]) / 2,
            (minV[3] + maxV[3]) / 2
        )
    end


    function transformBlockPos(rawPos, bsize, buildCenter, rotCF, offset)
