local formationMode = "idle"
local formationAccumulator = 0


local FOLLOW_SIDE_SPACING   = 4
local FOLLOW_ROW_DEPTH      = 3.5
local FOLLOW_DISTANCE       = 3
local FOLLOW_WALK_STOP_DIST = 2.4
