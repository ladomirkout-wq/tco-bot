            return HttpService:JSONEncode(blocks)
        end)
        if not ok then
            chat("❌ JSON encode failed: " .. tostring(encoded))
            return
        end


        local writeOk, writeErr = pcall(function()
            writefile(filename, encoded)
        end)
        if not writeOk then
            chat("❌ Write failed: " .. tostring(writeErr))
            return
        end


        chat(string.format("✅ Saved %d blocks to %s", #blocks, filename))
    end


    -- ── Core block placer — fully scoped, zero globals ────────────────────────


    buildblock = function(pos, texture, color, bsize, bsizev3, premadebuild, origmaterial, sprays, anchored, collide, isDetail)
        if anchored == nil then anchored = true end
        if collide  == nil then collide  = true end
        if isDetail == nil then
            isDetail = bsizev3 ~= nil and (
                bsizev3.X ~= gridSize or
                bsizev3.Y ~= gridSize or
                bsizev3.Z ~= gridSize
            )
        end


        local needsresize = false


        -- Per-call locals — no globals touched
        local localBuilt     = false
        local localChildcube = nil


        pcall(function()
            LocalPlayer.Backpack.Build.Parent = LocalPlayer.Character
        end)


        local finalPos = isDetail and pos or snap(pos)


        if bsize == nil then
            if isDetail then
                bsize = "detailed"
            else
                bsize = "normal"
                if LocalPlayer.PlayerGui:FindFirstChild("Build") and
                   LocalPlayer.PlayerGui.Build:FindFirstChild("Button") then
                    bsize = LocalPlayer.PlayerGui.Build.Button.Text
                end
            end
            if bsizev3 == nil and not isDetail and oldprt and
               oldprt.Position ~= roundBuildPos(pos) then
                bsize       = "detailed"
                needsresize = true
                bsizev3     = Vector3.new(4, 4, 4)
                pos         = Vector3.new(
                    (pos.X - (bsizev3.X / 2)) + 0.5,
                    (pos.Y - (bsizev3.Y / 2)) + 0.5,
                    (pos.Z - (bsizev3.Z / 2)) + 0.5
                )
                finalPos = pos
            end
        end


        -- ── Scoped watcher — this call only ───────────────────────────────────
        local watchFolder = cfolder:FindFirstChild(LocalPlayer.Name) or cfolder
        local placementConn = watchFolder.ChildAdded:Connect(function(child)
            if localBuilt then return end
            localBuilt     = true
            localChildcube = child
            -- Keep cubehistory working
            historynum = (historynum % historymax) + 1
            cubehistory[historynum] = child
            if buildingtoxify then toxifybrick = child end
        end)


        -- ── Place loop ────────────────────────────────────────────────────────
        local deadline = tick() + BLOCK_TIMEOUT


        repeat
            if LocalPlayer.Character and
               not LocalPlayer.Character:FindFirstChild("Build") and
               LocalPlayer.Backpack:FindFirstChild("Build") then
                LocalPlayer.Backpack.Build.Parent = LocalPlayer.Character
            end


            if LocalPlayer.Character and LocalPlayer.Character:FindFirstChild("Build") then
                local bt = LocalPlayer.Character.Build
                local ev = (bt:FindFirstChild("origevent") and bt.origevent) or
                           (bt:FindFirstChild("Script") and bt.Script:FindFirstChild("Event"))
                if ev then
                    pcall(function()
                        ev:FireServer(workspace.Terrain, Enum.NormalId.Top, finalPos, bsize)
                    end)
                end
            end


            teleportToBuildPos(finalPos)
            task.wait(VERIFY_WAIT)


            if localBuilt and localChildcube then break end
            if blockConfirmedOnServer(pos, bsizev3 or Vector3.new(gridSize, gridSize, gridSize), isDetail) then
                break
            end


        until stopped or tick() > deadline


        placementConn:Disconnect()
        localBuilt = false


        -- ── Paint / material ──────────────────────────────────────────────────
        if localChildcube and (
            (typeof(color) == "Color3" and color ~= defaultcolor) or texture
        ) and (
            LocalPlayer.Backpack:FindFirstChild("Paint") or
            LocalPlayer.Character:FindFirstChild("Paint")
        ) and (
            (colorbool and premadebuild ~= nil) or not colorbool
        ) then
            local pp   = localChildcube.Position + localChildcube.Size / 2
            local mode = "color"
            if texture and color then
                mode = "both \u{1F91D}"
            elseif texture then
                mode = "material"
            end
            local args = {
                localChildcube, Enum.NormalId.Top, pp,
                mode, color or nil, texture or "tiles", ""
            }
            pcall(function() LocalPlayer.Backpack.Paint.Parent = LocalPlayer.Character end)


            local paintDeadline = tick() + BLOCK_TIMEOUT
            repeat
                if LocalPlayer.Character and
                   not LocalPlayer.Character:FindFirstChild("Paint") and
                   LocalPlayer.Backpack:FindFirstChild("Paint") then
                    LocalPlayer.Backpack.Paint.Parent = LocalPlayer.Character
                end
                if LocalPlayer.Character and LocalPlayer.Character:FindFirstChild("Paint") then
                    local pt = LocalPlayer.Character.Paint
                    local ev = (pt:FindFirstChild("origevent") and pt.origevent) or
                               (pt:FindFirstChild("Script") and pt.Script:FindFirstChild("Event"))
                    if ev then
                        pcall(function() ev:FireServer(table.unpack(args)) end)
                    end
                end
                teleportToBuildPos(pp)
                task.wait(VERIFY_WAIT)
            until not localChildcube or not localChildcube.Parent
                or localChildcube.Color == color
                or (texture and localChildcube.Material == Enum.Material[origmaterial or "SmoothPlastic"])
                or stopped or skipblock
                or tick() > paintDeadline
        end


        -- ── Anchor toggle ─────────────────────────────────────────────────────
        if localChildcube and LocalPlayer.Character:FindFirstChild("Paint") and
           localChildcube.Anchored ~= anchored then
            local pp   = localChildcube.Position + localChildcube.Size / 2
            local args = {
                localChildcube, Enum.NormalId.Top, pp,
                "material", nil, "anchor", ""
            }
            local anchorDeadline = tick() + BLOCK_TIMEOUT
            repeat
                if LocalPlayer.Character and
                   not LocalPlayer.Character:FindFirstChild("Paint") and
                   LocalPlayer.Backpack:FindFirstChild("Paint") then
                    LocalPlayer.Backpack.Paint.Parent = LocalPlayer.Character
                end
                if LocalPlayer.Character and LocalPlayer.Character:FindFirstChild("Paint") then
                    local pt = LocalPlayer.Character.Paint
                    local ev = (pt:FindFirstChild("origevent") and pt.origevent) or
                               (pt:FindFirstChild("Script") and pt.Script:FindFirstChild("Event"))
                    if ev then
                        pcall(function() ev:FireServer(table.unpack(args)) end)
                    end
                end
                teleportToBuildPos(pp)
                task.wait(1)
            until not localChildcube or not localChildcube.Parent
                or localChildcube.Anchored == anchored
                or stopped or skipblock
                or tick() > anchorDeadline
        end


        -- ── Collide toggle ────────────────────────────────────────────────────
        if localChildcube and LocalPlayer.Character:FindFirstChild("Paint") and
           localChildcube.CanCollide ~= collide then
            local pp   = localChildcube.Position + localChildcube.Size / 2
            local args = {
                localChildcube, Enum.NormalId.Top, pp,
                "material", nil, "collide", ""
            }
            local collideDeadline = tick() + BLOCK_TIMEOUT
            repeat
                if LocalPlayer.Character and
                   not LocalPlayer.Character:FindFirstChild("Paint") and
                   LocalPlayer.Backpack:FindFirstChild("Paint") then
                    LocalPlayer.Backpack.Paint.Parent = LocalPlayer.Character
                end
                if LocalPlayer.Character and LocalPlayer.Character:FindFirstChild("Paint") then
                    local pt = LocalPlayer.Character.Paint
                    local ev = (pt:FindFirstChild("origevent") and pt.origevent) or
                               (pt:FindFirstChild("Script") and pt.Script:FindFirstChild("Event"))
                    if ev then
                        pcall(function() ev:FireServer(table.unpack(args)) end)
                    end
                end
                teleportToBuildPos(pp)
                task.wait(1)
            until not localChildcube or not localChildcube.Parent
                or localChildcube.CanCollide == collide
                or stopped or skipblock
                or tick() > collideDeadline
        end


        -- ── Sprays ────────────────────────────────────────────────────────────
        if localChildcube and sprays ~= nil and (
            LocalPlayer.Backpack:FindFirstChild("Paint") or
            LocalPlayer.Character:FindFirstChild("Paint")
        ) then
            local pp = localChildcube.Position + localChildcube.Size / 2
            for _, v in pairs(sprays) do
                if stopped or skipblock then break end
                local payload = v[3]
                if (not payload or payload == "") and type(v[2]) == "string" and v[2] ~= "" then
                    payload = v[2]
                end
                local args = {
                    localChildcube, Enum.NormalId[v[1]], pp,
                    "material", nil, "spray", payload or ""
                }
                pcall(function() LocalPlayer.Backpack.Paint.Parent = LocalPlayer.Character end)
                if LocalPlayer.Character:FindFirstChild("Paint") then
                    local pt = LocalPlayer.Character.Paint
                    local ev = (pt:FindFirstChild("origevent") and pt.origevent) or
                               (pt:FindFirstChild("Script") and pt.Script:FindFirstChild("Event"))
                    if ev then
                        pcall(function() ev:FireServer(table.unpack(args)) end)
                    end
                end
                teleportToBuildPos(pp)
                task.wait(0.25)
            end
        end


        -- ── Resize ────────────────────────────────────────────────────────────
        if localChildcube and bsizev3 ~= nil and (
            bsizev3.X ~= gridSize or
            bsizev3.Y ~= gridSize or
            bsizev3.Z ~= gridSize or
            needsresize
        ) and (
            LocalPlayer.Character:FindFirstChild("Shape") or
            LocalPlayer.Backpack:FindFirstChild("Shape")
        ) then
            if not LocalPlayer.Character:FindFirstChild("Shape") then
                LocalPlayer.Backpack.Shape.Parent = LocalPlayer.Character
            end
            local axes = {
                { Enum.NormalId.Right, "X" },
                { Enum.NormalId.Top,   "Y" },
                { Enum.NormalId.Back,  "Z" },
            }
            for _, axis in ipairs(axes) do
                local face, dim = axis[1], axis[2]
                if not localChildcube or not localChildcube.Parent then break end
                if localChildcube.Size[dim] == bsizev3[dim] then continue end


                local resizeDeadline = tick() + BLOCK_TIMEOUT
                repeat
                    if not localChildcube or not localChildcube.Parent then break end
                    local pp  = localChildcube.Position + localChildcube.Size / 2
                    local dir = nil
                    if localChildcube.Size[dim] > bsizev3[dim] then
                        dir = "decrease"
                    elseif localChildcube.Size[dim] < bsizev3[dim] then
                        dir = "increase"
                    end
                    if not dir then break end
                    if not LocalPlayer.Character:FindFirstChild("Shape") and
                       LocalPlayer.Backpack:FindFirstChild("Shape") then
                        LocalPlayer.Backpack.Shape.Parent = LocalPlayer.Character
                    end
                    if LocalPlayer.Character:FindFirstChild("Shape") then
                        local sh = LocalPlayer.Character.Shape
                        local ev = (sh:FindFirstChild("origevent") and sh.origevent) or
                                   (sh:FindFirstChild("Script") and sh.Script:FindFirstChild("Event"))
                        if ev then
                            pcall(function()
                                ev:FireServer(localChildcube, face, pp, dir)
                            end)
                        end
                    end
                    teleportToBuildPos(pp)
                    task.wait(resizewait)
                until not localChildcube or not localChildcube.Parent
                    or localChildcube.Size[dim] == bsizev3[dim]
                    or (dir == "decrease" and localChildcube and localChildcube.Size[dim] <= 1)
                    or stopped or skipblock
                    or tick() > resizeDeadline
            end
        end


        skipblock = false
        if oldprt then oldprt:Destroy() end
        localChildcube = nil
    end


    -- ── RunBuildSlice — slice first, sort slice, zero global crossfire ────────


    function RunBuildSlice(manifestId, filename)
        filename = filename or MANIFEST_FILE
        if not isBot then
            displayLocalMessage("Build only runs on bot accounts.")
            return
        end


        local manifest, err = parseManifest(filename)
        if not manifest then
            displayLocalMessage(err or "Manifest load failed.")
            return
        end


        local roster      = getBotRoster()
        local myIndex     = getLocalBotIndex(roster) or 1
        local botCount    = math.max(#roster, 1)
        local rotCF       = manifest.rotCF
        local offset      = manifest.offset
        local allBlocks   = manifest.blocks
        local buildCenter = (rotCF or offset) and computeBuildCenter(allBlocks) or nil


        -- Slice first — each bot sorts only its own assigned blocks
        local myBlocks = {}
        for i, v in ipairs(allBlocks) do
            if ((i - 1) % botCount) + 1 == myIndex then
                table.insert(myBlocks, v)
            end
        end
        myBlocks = sortBlocksByDistanceFromSpawn(myBlocks)


        if #myBlocks == 0 then
            displayLocalMessage("No blocks assigned to " .. LocalPlayer.Name)
            return
        end


        stopped   = false
        skipblock = false


        local total      = #myBlocks
        local placed     = 0
        local hardFailed = {}


        displayLocalMessage(string.format(
            "Build started: %d blocks assigned to %s", total, LocalPlayer.Name
        ))


        -- ── Pass 1 ────────────────────────────────────────────────────────────
        for i, v in ipairs(myBlocks) do
            if stopped then break end


            local bsz    = v.bsz
            local rawPos = Vector3.new(v.p[1], v.p[2], v.p[3])
            local pos    = transformBlockPos(rawPos, bsz, buildCenter, rotCF, offset)


            if pos.X ~= pos.X or pos.Y ~= pos.Y or pos.Z ~= pos.Z then continue end
            if pos.Magnitude > 100000 then continue end


            if blockConfirmedOnServer(pos, bsz, v.isDetail) then
                placed = placed + 1
                continue
            end


            createpartrepl(pos, bsz, v.col, swappedmaterials[v.mat] or Enum.Material.SmoothPlastic)
            buildblock(pos, v.mat, v.col, nil, bsz, true, nil, v.sprays, v.anch, v.coll, v.isDetail)


            if blockConfirmedOnServer(pos, bsz, v.isDetail) then
                placed = placed + 1
                v.placed = true
            else
                table.insert(hardFailed, v)
            end


            if i % 20 == 0 then
                displayLocalMessage(string.format(
                    "Progress: %d/%d (%d pending)", placed, total, #hardFailed
                ))
            end


            task.wait(0)
        end


        if stopped then
            displayLocalMessage("Build stopped.")
            return
        end


        -- ── Verification sweeps ───────────────────────────────────────────────
        if #hardFailed > 0 then
            displayLocalMessage(string.format(
                "Verification: %d blocks need retry sweeps", #hardFailed
            ))


            local retryQueue = hardFailed
            local pass       = 0


            while #retryQueue > 0 and pass < VERIFY_PASSES and not stopped do
                pass = pass + 1
                local stillFailed = {}


                for _, v in ipairs(retryQueue) do
                    if stopped then break end


                    local bsz    = v.bsz
                    local rawPos = Vector3.new(v.p[1], v.p[2], v.p[3])
                    local pos    = transformBlockPos(rawPos, bsz, buildCenter, rotCF, offset)


                    if blockConfirmedOnServer(pos, bsz, v.isDetail) then
                        placed = placed + 1
                        continue
                    end


                    createpartrepl(pos, bsz, v.col, swappedmaterials[v.mat] or Enum.Material.SmoothPlastic)
                    buildblock(pos, v.mat, v.col, nil, bsz, true, nil, v.sprays, v.anch, v.coll, v.isDetail)


                    if blockConfirmedOnServer(pos, bsz, v.isDetail) then
                        placed = placed + 1
                    else
                        table.insert(stillFailed, v)
                    end


                    task.wait(0)
                end


                retryQueue = stillFailed


                if #retryQueue > 0 then
                    displayLocalMessage(string.format(
                        "Sweep %d/%d done — %d still unplaced", pass, VERIFY_PASSES, #retryQueue
                    ))
                    task.wait(0.5)
                end
            end


            if #retryQueue > 0 then
                displayLocalMessage(string.format(
                    "⚠️ %d blocks permanently unplaceable after %d sweeps",
                    #retryQueue, VERIFY_PASSES
                ))
            else
                displayLocalMessage("✅ All blocks verified on server.")
            end
        end


        displayLocalMessage(string.format(
            "Build complete: %d/%d placed by %s", placed, total, LocalPlayer.Name
        ))
    end


    function StopBuild()
        stopped   = true
        skipblock = true
    end
end




