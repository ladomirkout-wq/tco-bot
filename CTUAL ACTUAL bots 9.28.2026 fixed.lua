local function computeFollowCFrame(ownerRoot, roster, index)
    local count  = math.max(#roster, 1)
    local perRow = math.clamp(math.ceil(math.sqrt(count)), 2, 5)
    local row    = math.floor((index - 1) / perRow)
    local col    = (index - 1) % perRow
    local rowStart  = row * perRow
    local rowCount  = math.min(perRow, count - rowStart)
    local centerOff = col - ((rowCount - 1) / 2)
    return ownerRoot.CFrame * CFrame.new(
        centerOff * FOLLOW_SIDE_SPACING, 0,
        FOLLOW_DISTANCE + row * FOLLOW_ROW_DEPTH
    )
end


local function computeFormationCFrame(ownerRoot, roster, index)
    local count = math.max(#roster, 1)
    local O   = ownerRoot.Position
    local R   = ownerRoot.CFrame.RightVector
    local L   = ownerRoot.CFrame.LookVector
    local U   = ownerRoot.CFrame.UpVector
    local sp  = SHAPE_SPACING
    local rad = SHAPE_RADIUS
    local dist = SHAPE_DISTANCE


    local function faceOwner(pos) return CFrame.lookAt(pos, O) end
    local function faceFwd(pos)   return CFrame.lookAt(pos, pos + L) end


    if formationMode == "line" then
        local centerOff = index - ((count + 1) / 2)
        local base = ownerRoot.CFrame * CFrame.new(0, 0, LINE_DISTANCE)
        local pos  = base.Position + R * (centerOff * LINE_SPACING)
        return CFrame.lookAt(pos, pos + L)


    elseif formationMode == "circle" then
        local angle = ((index - 1) / count) * math.pi * 2
        local pos = O + R * math.cos(angle) * CIRCLE_RADIUS
                      + L * math.sin(angle) * CIRCLE_RADIUS
        return CFrame.lookAt(pos, O)


        elseif formationMode == "upsidedownt" then
    local barCount  = math.max(math.ceil(count * 0.6), 3)
    local stemCount = math.max(count - barCount, 0)


    if index <= barCount then
        local centerOff = (index - 1) - (barCount - 1) / 2
        local pos = O + L * dist + R * (centerOff * sp)
        return faceFwd(pos)
    else
        local stemIndex = index - barCount
        local pos = O + L * dist + U * (stemIndex * sp)
        return faceFwd(pos)
    end


    elseif formationMode == "orbit" then
        local angle = (os.clock() * ORBIT_SPEED) + (((index - 1) / count) * math.pi * 2)
        local pos = O + R * math.cos(angle) * ORBIT_RADIUS
                      + L * math.sin(angle) * ORBIT_RADIUS
        return CFrame.lookAt(pos, O)


    elseif formationMode == "tower" then
        local base = ownerRoot.CFrame * CFrame.new(0, 0, -TOWER_DISTANCE)
        local pos  = base.Position + Vector3.new(0, (index - 1) * TOWER_SPACING, 0)
        return CFrame.lookAt(pos, pos + L)


    elseif formationMode == "scatter" then
        local angle  = math.rad((index * 137) % 360)
        local radius = SCATTER_RADIUS + ((index % 4) * 2)
        local pos    = O + R * math.cos(angle) * radius + L * math.sin(angle) * radius
        return CFrame.lookAt(pos, O)


    elseif formationMode == "square" then
        local t    = ((index - 1) % count) / count * 4
        local side = math.floor(t); local f = t - side
        local sx, sz
        if side == 0 then      sx, sz = -rad + 2*rad*f, -rad
        elseif side == 1 then  sx, sz =  rad,           -rad + 2*rad*f
        elseif side == 2 then  sx, sz =  rad - 2*rad*f,  rad
        else                   sx, sz = -rad,             rad - 2*rad*f end
        return faceOwner(O + R*sx + L*sz)


    elseif formationMode == "diamond" then
        local verts = { {0,-rad},{rad,0},{0,rad},{-rad,0},{0,-rad} }
        local t = ((index-1)%count)/count*4; local side = math.floor(t); local f = t-side
        local a, b = verts[side+1], verts[side+2]
        return faceOwner(O + R*(a[1]+(b[1]-a[1])*f) + L*(a[2]+(b[2]-a[2])*f))


    elseif formationMode == "grid" then
        local cols = math.max(math.ceil(math.sqrt(count)), 1)
        local row  = math.floor((index-1)/cols); local col = (index-1)%cols
        return faceFwd(O + L*dist + R*((col-(cols-1)/2)*sp) + L*(row*sp))


    elseif formationMode == "wall" then
        local cols = math.max(math.ceil(math.sqrt(count)), 1)
        local row  = math.floor((index-1)/cols); local col = (index-1)%cols
        return faceFwd(O + L*dist + R*((col-(cols-1)/2)*sp) + U*(row*sp))


    elseif formationMode == "triangle" then
        local row, placed = 0, 0
        while placed + (row+1) < index do placed = placed+(row+1); row = row+1 end
        local posInRow = index - placed - 1
        return faceFwd(O + L*dist + R*((posInRow - row/2)*sp) + L*(row*sp))


    elseif formationMode == "pyramid" then
        local n = 1
        while n*(n+1)/2 < count do n = n+1 end
        local row, placed, width = 0, 0, n
        while placed+width < index and width > 1 do
            placed = placed+width; row = row+1; width = n-row
        end
        local posInRow = index - placed - 1
        return faceFwd(O + L*dist + R*((posInRow-(width-1)/2)*sp) + U*(row*sp))


    elseif formationMode == "cross" then
        local arm = math.floor((index-1)/4); local dir = (index-1)%4
        local off = (arm+1)*sp; local dx, dz = 0, 0
        if dir == 0 then dz = off elseif dir == 1 then dz = -off
        elseif dir == 2 then dx = off else dx = -off end
        return faceOwner(O + R*dx + L*dz)


    elseif formationMode == "wedge" then
        local depth    = math.ceil(index/2)
        local sideSign = (index%2 == 0) and 1 or -1
        return faceFwd(O + L*dist + R*(sideSign*depth*sp*0.7) - L*(depth*sp))


    elseif formationMode == "arc" then
        local a   = (count == 1) and 0.5 or ((index-1)/(count-1))
        local ang = math.rad(-90 + a*180)
        return faceOwner(O + R*math.sin(ang)*rad + L*math.cos(ang)*rad)


    elseif formationMode == "zigzag" then
        local sideSign = (index%2 == 0) and 1 or -1
        return faceFwd(O + L*dist + L*((index-1)*sp) + R*(sideSign*sp))


    elseif formationMode == "star" then
        local t = ((index-1)%count)/count; local ang = t*math.pi*2
        local rr = (math.floor(t*10)%2 == 0) and rad or rad*0.45
        return faceOwner(O + R*math.cos(ang)*rr + L*math.sin(ang)*rr)


    elseif formationMode == "spiral" then
        local ang = (index-1)*0.6; local rr = 3+(index-1)*sp*0.35
        return faceOwner(O + R*math.cos(ang)*rr + L*math.sin(ang)*rr)


    elseif formationMode == "heart" then
        local s = rad/16; local t = ((index-1)%count)/count*math.pi*2
        local hx = 16*math.sin(t)^3
        local hz = 13*math.cos(t) - 5*math.cos(2*t) - 2*math.cos(3*t) - math.cos(4*t)
        return faceOwner(O + R*(hx*s) + L*(hz*s))
    end


    return nil
end


-- Formation heartbeat — runs on EVERY client (bot or not). Bots move
-- themselves; the owner client does nothing because it's not in the bot roster.
RunService.Heartbeat:Connect(function(dt)
    if formationMode == "idle" then return end


    -- Only bot accounts should physically move in formation
    if not isBot then return end


    formationAccumulator = formationAccumulator + dt
    if formationAccumulator < 0.03 then return end
    formationAccumulator = 0


    local ownerRoot = getFormationOwnerRoot()
    if not ownerRoot then return end


    local roster = getBotRoster()
    local index  = getLocalBotIndex(roster)
    if not index then return end  -- this bot isn't in the roster


    if formationMode == "follow" then
        local char = LocalPlayer.Character
        local hum  = char and char:FindFirstChildOfClass("Humanoid")
        local root = char and char:FindFirstChild("HumanoidRootPart")
        if not root or not hum or hum.Health <= 0 then return end


        local targetPos = computeFollowCFrame(ownerRoot, roster, index).Position
        local dist = (root.Position - targetPos).Magnitude


        if dist > FOLLOW_TELEPORT_DIST then
            safeTeleport(CFrame.lookAt(targetPos, targetPos + ownerRoot.CFrame.LookVector))
            lastFollowMoveTo = 0; followStuckSince = nil; followStuckCheckPos = nil
            return
        end


        if dist > FOLLOW_WALK_STOP_DIST then
            local now = os.clock()
            if now - lastFollowMoveTo > FOLLOW_REPATH_INT then
                lastFollowMoveTo = now
                pcall(function() hum:MoveTo(targetPos) end)
            end
            if not followStuckCheckPos then
                followStuckCheckPos = root.Position
                followStuckSince    = now
            elseif (root.Position - followStuckCheckPos).Magnitude < 2 then
                if followStuckSince and now - followStuckSince > FOLLOW_STUCK_SECS then
                    hum.Jump = true
                    followStuckSince = now
                end
            else
                followStuckCheckPos = root.Position
                followStuckSince    = now
            end
        else
            pcall(function() hum:MoveTo(root.Position) end)
            followStuckSince = nil; followStuckCheckPos = nil
        end
        return
    end


    local cf = computeFormationCFrame(ownerRoot, roster, index)
    if cf then safeTeleport(cf) end
end)




